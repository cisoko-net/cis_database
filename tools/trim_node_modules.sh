#!/usr/bin/env bash
# Trims a node_modules folder to what cis_database runs: mysql2, sql.js's
# asm build (server.js loads dist/sql-asm.js) and what they load. Type
# packages, typings, tests, examples, browser builds and project files of
# the packages go; every LICENSE and README stays.
#
# Usage: tools/trim_node_modules.sh <path to node_modules>
set -euo pipefail

nm="${1:?usage: trim_node_modules.sh <node_modules>}"
[ -d "$nm/mysql2" ] || { echo "no mysql2 in $nm" >&2; exit 1; }

rm -rf "$nm/.cache" "$nm/@types" "$nm/undici-types"
find "$nm/sql.js/dist" -type f ! -name sql-asm.js -delete
find "$nm" -type f -name '*.d.ts' -delete
rm -rf \
    "$nm/mysql2/typings" \
    "$nm/lru.min/browser" \
    "$nm/sql.js/.devcontainer"
rm -f \
    "$nm/generate-function/.travis.yml" \
    "$nm/generate-function/example.js" \
    "$nm/generate-function/test.js" \
    "$nm/safer-buffer/tests.js" \
    "$nm/safer-buffer/Porting-Buffer.md" \
    "$nm/is-property/.npmignore" \
    "$nm/sql.js/.eslintrc.js" \
    "$nm/sql.js/.jsdoc.config.json" \
    "$nm/sql.js/.nojekyll" \
    "$nm/sql.js/AUTHORS" \
    "$nm/sql.js/CONTRIBUTING.md" \
    "$nm/sql.js/documentation_index.md" \
    "$nm/sql.js/logo.svg"
